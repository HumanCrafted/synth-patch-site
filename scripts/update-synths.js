// Rebuilds the "Our Growing Synth Collection" grid in index.html from the
// app's public synth list, so the marketing site never falls behind the app.
// Each card links to the synth's page on the app.
//
// Runs during `npm run build` and can be run on its own: `npm run update-synths`.
// If the app can't be reached, index.html is left as it is (the committed grid
// stays in place), so a build never ships an empty grid.

const fs = require('fs');
const path = require('path');

const APP_URL = 'https://app.synthpatch.io';
const API_URL = process.env.SYNTHS_API_URL || `${APP_URL}/api/synths`;
const INDEX_PATH = path.join(__dirname, '..', 'index.html');
const START = /( *)<!-- SYNTH-GRID:START[^>]*-->/;
const END = '<!-- SYNTH-GRID:END -->';
const MOBILE_COUNT = 6; // cards shown before "View More" on mobile
const DESKTOP_COUNT = 12; // cards shown before "View More" from the sm breakpoint up

const escapeHtml = (value) =>
  String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

function card(synth, extraClass = '') {
  const name = `${synth.manufacturer} ${synth.model}`;
  const href = `${APP_URL}/synth/${encodeURIComponent(synth.slug)}`;
  const classes = `card rounded-2xl overflow-hidden block transition-shadow hover:shadow-lg${extraClass ? ` ${extraClass}` : ''}`;
  return `        <!-- ${escapeHtml(name)} -->
        <a href="${href}" class="${classes}" data-umami-event="synths-card" data-umami-event-synth="${escapeHtml(synth.slug)}">
          <div class="bg-white p-4 flex items-center justify-center" style="height: 180px;">
            <img
              src="${escapeHtml(synth.thumbnail_url)}"
              alt="${escapeHtml(name)}"
              class="max-w-full max-h-full object-contain"
              loading="lazy"
            />
          </div>
          <div class="p-4">
            <p class="text-xs md:text-sm text-muted-foreground mb-1">${escapeHtml(synth.manufacturer)}</p>
            <p class="text-sm md:text-base font-semibold">${escapeHtml(synth.model)}</p>
          </div>
        </a>`;
}

function buildGrid(synths, indent) {
  const first = synths.slice(0, MOBILE_COUNT);
  const desktopOnly = synths.slice(MOBILE_COUNT, DESKTOP_COUNT);
  const rest = synths.slice(DESKTOP_COUNT);

  const initial = [
    ...first.map((s) => card(s)),
    // Shown up front from sm up; on mobile these appear in the expanded grid instead
    ...desktopOnly.map((s) => card(s, 'hidden sm:block')),
  ];
  const expanded = [
    ...desktopOnly.map((s) => card(s, 'sm:hidden')),
    ...rest.map((s) => card(s)),
  ];

  return `${indent}<!-- SYNTH-GRID:START (generated by scripts/update-synths.js from the app's synth list; edits here are overwritten) -->
      <!-- Initial Grid (first ${MOBILE_COUNT} on mobile, first ${DESKTOP_COUNT} from sm up) -->
      <div id="synth-grid-initial" class="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-6 md:gap-8">
${initial.join('\n\n')}
      </div>

      <!-- Expandable Grid (the rest; mobile also gets cards ${MOBILE_COUNT + 1}-${DESKTOP_COUNT} here) -->
      <div id="synth-grid-expanded" class="hidden grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-6 md:gap-8 mt-6 md:mt-8">
${expanded.join('\n\n')}
      </div>
      ${END}`;
}

async function main() {
  let synths;
  try {
    const response = await fetch(API_URL, { headers: { Accept: 'application/json' } });
    if (!response.ok) throw new Error(`HTTP ${response.status}`);
    const body = await response.json();
    synths = (body.data || []).filter(
      (s) => s.slug && s.manufacturer && s.model && s.thumbnail_url && s.is_listed !== false
    );
    if (synths.length === 0) throw new Error('no synths returned');
  } catch (error) {
    console.warn(`⚠️  Could not load synths from ${API_URL} (${error.message}); leaving the synth grid unchanged.`);
    return;
  }

  synths.sort((a, b) =>
    `${a.manufacturer} ${a.model}`.localeCompare(`${b.manufacturer} ${b.model}`, 'en', { sensitivity: 'base' })
  );

  let html = fs.readFileSync(INDEX_PATH, 'utf8');
  const startMatch = html.match(START);
  const endIndex = html.indexOf(END);
  if (!startMatch || endIndex === -1) {
    console.warn('⚠️  SYNTH-GRID markers not found in index.html; leaving it unchanged.');
    return;
  }

  html =
    html.slice(0, startMatch.index) +
    buildGrid(synths, startMatch[1]) +
    html.slice(endIndex + END.length);

  // Keep the "View All N Synthesizers" button label in sync
  html = html.replace(/data-synth-count="\d+"/, `data-synth-count="${synths.length}"`);

  fs.writeFileSync(INDEX_PATH, html);
  console.log(`✓ Synth grid updated with ${synths.length} synths from ${API_URL}`);
}

main();
